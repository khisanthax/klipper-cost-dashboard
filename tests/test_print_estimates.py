from io import BytesIO
import unittest
from unittest.mock import patch

from werkzeug.datastructures import FileStorage

from core.estimates import estimate_print
from core.gcode_metadata import extract_gcode_metadata_stream


class EstimateTests(unittest.TestCase):
    def test_orca_length_uses_only_explicit_conversion_and_billing_minimum(self):
        metadata = b"; generated by OrcaSlicer\n; estimated printing time = 30m\n; filament used [mm] = 12500\n"
        fields = {"hourly_rate": 2, "filament_price_per_kg": 20}
        upload = FileStorage(BytesIO(metadata), filename="sample.gcode")
        unknown = estimate_print(fields, upload)
        self.assertEqual(unknown["time_cost"], 2)
        self.assertIsNone(unknown["filament_grams"])
        self.assertIsNone(unknown["material_cost"])
        self.assertIsNone(unknown["total_cost"])
        converted = estimate_print({**fields, "grams_per_meter": 2}, upload)
        self.assertEqual(converted["filament_grams"], 25)
        self.assertEqual(converted["display_total"], "2.50")

    def test_profile_and_zero_hourly_rate(self):
        with patch("core.profiles.get_profile", return_value={
            "name": "Verified", "filament_mode": "per_meter", "filament_rate": 0.1, "grams_per_meter": 2,
        }):
            result = estimate_print({
                "hourly_rate": 0, "duration_seconds": 1800,
                "filament_profile_id": "profile", "filament_grams": 20,
            })
        self.assertEqual(result["filament_price_per_kg"], 50)
        self.assertEqual(result["total_cost"], 1)

    def test_parser_ignores_commands_and_reads_footer_after_large_line(self):
        data = (
            b"G1 X100 estimated printing time = 1s\n" + b"M" * (2 * 1024 * 1024)
            + b"\n;TIME:3600\n; filament used [g] = 12.5\n"
        )
        result = extract_gcode_metadata_stream(BytesIO(data))
        self.assertEqual((result.time_s, result.filament_g), (3600, 12.5))

    def test_invalid_numbers_and_non_gcode_upload(self):
        fields = {"hourly_rate": 2, "filament_price_per_kg": 20, "duration_seconds": 1800}
        for extra in ({"duration_seconds": "nan"}, {"filament_grams": -1}, {"hourly_rate": True}):
            with self.assertRaises(ValueError):
                estimate_print({**fields, **extra})
        with self.assertRaises(ValueError):
            estimate_print(fields, FileStorage(BytesIO(b";TIME:1"), filename="archive.zip"))
